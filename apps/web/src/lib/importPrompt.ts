export function importPromptFor(subject: SubjectCode | string): string {
  const code: SubjectCode = subject === 'english' || subject === 'cs' ? subject : 'math';
  const format = code === 'english' ? ENGLISH_FORMAT : code === 'cs' ? CS_FORMAT : MATH_FORMAT;
  const rules = code === 'english' ? ENGLISH_RULES : code === 'cs' ? CS_RULES : MATH_RULES;
  const kp = code === 'english' ? ENGLISH_KP : code === 'cs' ? CS_KP : MATH_KP;
  const lastExtra =
    code === 'english'
      ? '6. 全篇不许出现 $ 和任何反斜杠命令；英文原句、阅读材料一个字都不许改，原文不许截断成「…」\n7. **类型** 只能是「选择题」或「翻译题」；翻译题不要写 **选项** 行，选择题答案只写字母'
      : code === 'cs'
        ? '6. 代码用三反引号包起来，不要写成 LaTeX 公式；关键字大小写照抄原文'
        : '6. 每个数学式子都要用 $...$ 包起来，包括选项里的式子；分数线、上下标与原题一致';

  return `${HEADER}

${format}

${rules}

${noteSection(code)}

━━━ 四、考点编码表（只能从中选择，别的科目的编号一律不许用）━━━

${kp}

${BREAKPOINT}

━━━ 六、其他硬性要求 ━━━

1. 直接从「### 错题1」开始输出，前面不要任何说明文字，不要用代码块包裹整个输出
2. 同一道题问过多次只整理一次
3. 超过 15 道就先输出最近的 15 道，最后一行写「（还有 N 道未列出）」，此时不要写断点标记，等我回复「继续」再输出下一批
4. 题目数字、分数线、上下标、英文单词必须与原题完全一致，不许改动原题
5. 对话里没有明确答案的题，按你当时讲解的内容补全
${lastExtra}`;
}

/** 默认（数学）提示词：兼容旧调用点 */
export const IMPORT_PROMPT = importPromptFor('math');

/**
 * 复制文本：优先 Clipboard API，非安全上下文（局域网 http）退回复选复制。
 * @param text 待复制文本
 * @returns 是否复制成功
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // 继续走兜底
  }
  try {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.setAttribute('readonly', '');
    ta.style.position = 'fixed';
    ta.style.top = '-9999px';
    ta.style.opacity = '0';
    document.body.appendChild(ta);
    ta.select();
    ta.setSelectionRange(0, text.length);
    const ok = document.execCommand('copy');
    document.body.removeChild(ta);
    return ok;
  } catch {
    return false;
  }
}
